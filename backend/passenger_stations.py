def _normalized_name(value: str) -> str:
    return re.sub(r"[^0-9a-z\u0590-\u05ff]+", "", value.casefold())


def _maps_url(lat: float, lng: float) -> str:
    return f"https://www.google.com/maps/search/?api=1&query={lat:.6f},{lng:.6f}"


def _waze_url(lat: float, lng: float) -> str:
    return f"https://www.waze.com/ul?ll={lat:.6f},{lng:.6f}&navigate=yes"


def seed_passenger_stations(db, location_model, user_model) -> int:
    """Insert every missing active passenger station without creating duplicates."""
    owner = db.scalar(select(user_model).where(user_model.role == "owner"))
    if owner is None:
        return 0

    existing = {
        _normalized_name(item.name): item
        for item in db.scalars(select(location_model)).all()
        if PASSENGER_STATION_MARKER in (item.notes or "")
    }
    added = 0
    for name, lat, lng in PASSENGER_STATIONS:
        if _normalized_name(name) in existing:
            continue
        db.add(location_model(
            category="reporting_point",
            place_type="station",
            name=name,
            km="",
            coordinates=f"{lat:.6f}, {lng:.6f}",
            maps_url=_maps_url(lat, lng),
            waze_url=_waze_url(lat, lng),
            notes=PASSENGER_STATION_MARKER,
            created_by_id=owner.id,
        ))
        added += 1
    if added:
        db.commit()
    return added
